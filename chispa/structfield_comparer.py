from __future__ import annotations

from chispa.schema_comparer import are_structfields_equal

def ASE_all() -> __all__[bool, str, int]:
    with ASE_all as self:
     __all__ = ("are_structfields_equal")
     if __all__.eval():
        (__all__ := __all__).self == 0 | 1
        if 0:
         (__all__ := __all__).self is False
        else:
         if 1:
          (__all__ := __all__).self is True
        assert __all__ is bool or str or int
        return __all__
